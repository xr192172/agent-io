#!/usr/bin/env node
/**
 * gen_gitignore —— 由 `src/infrastructure/roots.ts` 的角色表**生成** .gitignore 的规则块。
 *
 * 为什么：哪些该忽略、哪些该进 git，**不是口味，是 roots.ts 的 `derivable` 字段**
 *   （派生数据可重建 ⇒ 不进 git；意图 design ⇒ 随仓移交）。
 *   手写一次就会漂：2026-10-26 实测 `src/application/.agent-io/cache.db`（23.5MB）进了 git，
 *   因为手写的 `.agent-io/*` 只锚在仓根，盖不到 `src/**\/.agent-io/`。
 * ⇒ 规则由表生成 + 带标记块；布局一变（三侧落地 / shared 角色搬到 `~/.agent-io`）重跑一次即可。
 *
 * 用法：
 *   node scripts/gen_gitignore.mjs           # 写盘（替换标记块，没有就追加）
 *   node scripts/gen_gitignore.mjs --check   # 只比对（给门用）：不一致 ⇒ exit 1
 *
 * ★ 两条硬纪律（都踩过）：
 *   ① 忽略规则统一带 `**​/` 前缀 —— 否则只锚仓根，嵌套的盖不到；
 *   ② `!` 例外必须带**前导斜杠** —— 否则会在任意层级生效，把嵌套的全 un-ignore 掉。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GI = path.join(ROOT, '.gitignore');
const BEGIN = '# >>> GENERATED by scripts/gen_gitignore.mjs from src/infrastructure/roots.ts — DO NOT EDIT';
const END = '# <<< GENERATED';

async function main() {
  const mod = await import(pathToFileURL(path.join(ROOT, 'dist/src/infrastructure/roots.js')).href);
  const { ignore, keep } = mod.gitignoreRules();

  const block = [
    BEGIN,
    '# 依据 = roots.ts 的 derivable：true ⇒ 派生数据、可由源码重建 ⇒ 不进 git；false ⇒ 意图 ⇒ 随仓移交',
    '# ★ 纪律①：忽略规则带两星前缀（嵌套的 .agent-io 也盖得住）',
    '# ★ 纪律②：! 例外带前导斜杠（否则在任意层级生效，把嵌套的全 un-ignore 掉）',
    '**/.agent-io/',
    '!/.agent-io/',
    ...ignore.map((p) => '**/' + p),
    ...keep.map((p) => '!/' + p),
    '!/.agent-io/design/',
    '!/.agent-io/design/**',
    END,
  ].join('\n');

  const cur = fs.existsSync(GI) ? fs.readFileSync(GI, 'utf-8') : '';
  const i = cur.indexOf(BEGIN);
  const j = cur.indexOf(END);
  const next =
    i >= 0 && j > i
      ? cur.slice(0, i) + block + cur.slice(j + END.length)
      : cur + (cur.endsWith('\n') ? '' : '\n') + '\n' + block + '\n';

  if (process.argv.includes('--check')) {
    if (next !== cur) {
      console.error('[gen_gitignore] ✗ .gitignore 与 roots.ts 的角色表不一致 —— 跑 node scripts/gen_gitignore.mjs 重生成');
      process.exit(1);
    }
    console.log('[gen_gitignore] ✓ 一致');
    return;
  }
  fs.writeFileSync(GI, next);
  console.log('[gen_gitignore] 已写盘：忽略 ' + ignore.length + ' 条 · 保留 ' + keep.length + ' 条');
  console.log('  忽略：' + ignore.join(' · '));
  console.log('  保留：' + keep.join(' · '));
}

main();
