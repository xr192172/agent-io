/**
 * scan_bounds —— ★「扫描边界」的统一契约（所有**会扫仓库**的工具的自证字段）
 *
 * ─────────────────────────────────────────────────────────────
 * 为什么要有这个字段（用户的洞察，2026-09-29）
 * ─────────────────────────────────────────────────────────────
 *   > 「你作为 LLM 应该是**没有时间观念的**……**你会不会优先选择它？**」
 *   成立的那半句是：**对 LLM 来说 可信度 > 精度 > 速度** —— LLM 没时间感，但有**一轮一轮的
 *   余量成本**：一个**不可信的返回 = 多要一轮验证**。
 *   ⇒ LLM 会优先选「**能自证边界**」的工具，因为它省掉一轮验证。
 *
 * 本仓其实已经在走这条路（`skipped[]` / `candidateScan` / `excludedNonCode` / G11 回执产物门），
 * **只是覆盖不全、形状不统一**：同一个意思，`find_references` 叫 `candidateScan`、
 * `code_health`/`impact_analysis` 叫 `excludedNonCode`、闭包族叫 `skipped`。
 * ⇒ LLM 每换一个工具就得**重新认识一遍**（要先读 description 才知道它给不给边界、字段叫什么）。
 * 本文件就是那条统一的名字：**一个字段名，处处可用**。
 *
 * ─────────────────────────────────────────────────────────────
 * 形状（★ 最终形状 + 为什么这么定）
 * ─────────────────────────────────────────────────────────────
 *   scope      扫描口径**一句话**（"import 反向闭包" / "全仓文本提及" / "全项目源码（按代码语言口径）"）。
 *              为什么是自由文本而不是枚举：口径是**工具自己的事**（闭包 / 全文 / 索引 / 目录走查），
 *              枚举会逼着每加一种扫描法就改契约；一句话能让 LLM 直接读懂"它到底扫了什么"。
 *   scanned    实际扫了多少。两个槽位：`files`（文件数）/ `positions`（文本位置数）。
 *              为什么只有两个槽：这两个是**跨工具真正同义**的两把尺子；工具特有的细分读数见 `detail`。
 *   skipped    ★「少做了什么」——逐条 `{ path, why }`（`count` 用于"一族多个"的聚合，如按扩展名）。
 *              为什么必须有：§2d「少做了什么必须可见」。**没有它，`scanned` 就是一句无法证伪的话**。
 *              `path` 允许是**扩展名模式**（如 `**\/*.json`）—— 与逐文件路径同构，只是粒度是"族"。
 *   truncated  ★ 是否被边界**截断**（true = 结果**不完整**，别当全集用）。这是最有价值的一位：
 *              它把"扫了 3000 个文件"与"仓库其实有 9000 个"变成机器可判。
 *   detail     逃生舱：**核心三槽装不下的、该工具特有的数值读数**（如闭包文件数 / 文本层补召回条数）。
 *              值**只放数字**（键自述语义）⇒ 它不会退化成"什么都往里塞"的自由文本袋。
 *              为什么需要它（而不是把契约撑大）：`candidateScan` 的 `{closureFiles, textAdded,
 *              textScanned}` 是**该工具独有**的分解，进不了任何通用槽位；给它专用字段 = 每工具一个
 *              字段名（正是本笔要消灭的形态）。收进 `detail` 既不丢信息、又不污染通用三槽。
 *
 * ★ 挂在回执的**哪一层**：`data.bounds`（`wrapData` 的 `---DATA---` 里）。
 *   理由（要一致）：`bounds` 是**机器可判的读数**（数字 + 结构化 skipped），不是散文；
 *   而本仓回执的机器通道**唯一**就是 `data`（`src/registry/plumbing.ts` 的 `wrapData`）。
 *   放进 `message` 就只能靠正则抠（正是 P-A 门记的那类翻车），放顶层则与
 *   `message` / `---DATA---` 的既有约定打架。⇒ 一律 `data.bounds`。
 *
 * ★ 可选 vs 必填：**扫仓库类必带、其余不带**。
 *   只读一个文件 / 只查库 / 纯计算的工具（`edit_code` / `observe_judge` / `snapshot` …）
 *   **不该**被迫带它 —— 它们的边界就是入参，硬加只会产出"恒真的空话"，把这道门变成空门。
 *   ⇒ 类型上是 `bounds?: ScanBounds`（可选），"谁该带"由门（`tests/tools/scan_bounds_gate.test.ts`）
 *     按**声明式登记 + 棘轮**兜（存量不拦、新增即红）。
 *
 * ─────────────────────────────────────────────────────────────
 * ★ 装不下的（如实登记，**不硬塞**）
 * ─────────────────────────────────────────────────────────────
 *   本契约能无损容纳的 skipped 形态：**文件级** `{path, why}` 与**扩展名族级** `{path, count, why}`。
 *   装不下的三种（各有工具在用，**保留原字段**，不往这里硬塞）：
 *     ① 自由文本行（`import_project.skipped: string[]`）—— 它是"给人看的一句话"，没有路径主语；
 *     ② 分组语义（`harvest_from_url.skipped: {seeds: string[], reason}[]`）—— 主语是**一组种子**；
 *     ③ 非路径主语（`explore_code.index_skipped: {what, why}[]`）—— 主语是"什么东西"。
 *   ⇒ 这三种若也要收，契约就得长成 `Record<string, unknown>[]`（= 没有契约）。
 *     故本笔**只做能无损表达的那部分**，其余留在原字段并在提交信息「没验什么」里逐条登记。
 */

/** 一条「被跳过的」账目。`count` 用于一族多个的聚合（缺省 = 1 个）。 */
export interface ScanSkip {
  /** 被跳过的东西：文件路径（相对项目根，POSIX 分隔）**或**扩展名模式（如 `**\/*.json`） */
  path: string;
  /** 为什么跳过（少做了什么，可读） */
  why: string;
  /** 一族多个时的个数（如"该扩展名共 N 个文件"）；缺省 = 1 */
  count?: number;
}

/**
 * ★ 扫描边界 —— 所有「扫仓库」类工具的统一自证字段（LLM 靠它判断"有没有漏"）。
 * 挂载位置：回执 `data.bounds`（见文件头"挂在回执的哪一层"）。
 */
export interface ScanBounds {
  /** 扫描口径一句话（"import 反向闭包" / "全仓文本提及" / "全项目源码（按代码语言口径）" …） */
  scope: string;
  /** 实际扫了多少（files=文件数 / positions=文本位置数） */
  scanned: { files?: number; positions?: number };
  /** ★ 被跳过的（少做了什么，逐条可读） */
  skipped?: ScanSkip[];
  /** ★ 是否被边界截断（true = 结果不完整，别当全集用） */
  truncated?: boolean;
  /** 该工具特有的补充读数（核心三槽装不下的数值；键自述语义，值只放数字） */
  detail?: Record<string, number>;
}

/**
 * 「口径收紧的可见性」→ 统一 `skipped` 的唯一落点（health / impact 共用）。
 *
 * 由来：2026-09-29 源码集从"**可解析**"收到"**代码语言**"，`.json` 这类文件不再进图 ——
 * 若连"有几个、是什么"都不说，就是「**缺失是沉默的**」。
 * 原先 `health` / `impact` 各持一份 `{ext, count}[]`（`excludedNonCode`）；本笔把它收进
 * 统一形状的族级 `skipped`（`count` 保留，`ext` 落进 `path` 模式 ⇒ 无损），**一处实现**。
 */
export function boundsSkipFromExcluded(
  excluded: ReadonlyArray<{ ext: string; count: number }>,
  why = '非代码语言扩展名：不进调用 / 依赖图（口径收紧的可见性；文件真实存在，只是不算源码）',
): ScanSkip[] {
  return excluded.map((e) => ({ path: `**/*${e.ext}`, why, count: e.count }));
}
